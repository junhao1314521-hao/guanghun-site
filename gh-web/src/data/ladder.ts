/**
 * 分值 → 进度条宽度（相对全榜）：
 * 综合分直接映射；其余指标按「越大越好 / 越小越好」归一化，榜首恒为 100%。
 * 对比度 ∞ 视为满条。
 */
export function fillWidth(metric: LadderMetric, row: LadderRow): number {
  if (row.inf) return 100
  if (row.score === null) return 0
  if (metric.id === 'overall') return Math.max(0, Math.min(100, row.score))
  const vals = metric.rows.map((r) => r.score).filter((v): v is number => v !== null)
  if (!vals.length) return 0
  const lo = Math.min(...vals)
  const hi = Math.max(...vals)
  if (hi === lo) return 100
  const pct = metric.better === 'high' ? (row.score - lo) / (hi - lo) : (hi - row.score) / (hi - lo)
  return Math.max(2, Math.round(pct * 100))
}

/** 数值格式化：按指标小数位；∞ 显示为 ∞ */
export function formatScore(metric: LadderMetric, row: LadderRow): string {
  if (row.inf) return '∞'
  if (row.score === null) return '—'
  return row.score.toFixed(metric.digits)
}
